// Slownictwo minigry "Tlumaczenia" - angielskie slowo -> lista akceptowanych
// polskich odpowiedzi. Wzorem src/countries.js (tam: kraj -> warianty nazwy).
//
// Kazdy wpis w RAW to [angielskieSlowo, podstawowePolskieTlumaczenie, opcjonalnaListaDodatkowychWariantow].
// Zbudowany na tej podstawie SLOWKA[en] daje PODSTAWOWE tlumaczenie (do
// wyswietlenia w ewentualnym podsumowaniu), a getAkceptowaneWarianty(en)
// zwraca WSZYSTKIE zaakceptowane odpowiedzi (podstawowa + warianty),
// znormalizowane przez normalizePolish (patrz src/vanessa.js - ta sama
// funkcja jest juz uzywana w calym projekcie, wiec porownanie jest odporne
// na polskie znaki i wielkosc liter bez pisania wlasnej kopii).
//
// Dobor slownictwa: rzeczy codzienne, ktore polski czat streamu realnie zna -
// bez slownictwa specjalistycznego i archaizmow. Celowo POMIJAMY slowa
// wieloznaczne bez kontekstu, ktorych sama flashcardowa forma ("jedno slowo
// angielskie -> ?") nie rozstrzyga (np. "bank" - instytucja finansowa czy
// brzeg rzeki, "light" - swiatlo czy lekki, "right" - prawo/prawy/racja,
// "spring" - wiosna/sprezyna/skakac, "watch" - zegarek czy patrzec,
// "second" - sekunda czy drugi) - dla tych, ktore mimo wszystko zostaly (np.
// "market", "short", "hard", "free", "top", "line", "corner", "volume",
// "party", "iron", "pepper", "goal", "glass", "chips", "letter", "race",
// "cool", "dream"), podajemy w
// wariantach KOMPLET sensownych tlumaczen zamiast jednego, zeby nie odrzucac
// poprawnych odpowiedzi.
//
// Brak duplikatow po stronie angielskiej: sprawdzane w RUNTIME nizej (rzuca
// wyjatkiem przy ladowaniu modulu, gdyby ktos przez pomylke dodal ten sam
