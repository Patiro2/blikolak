/**
 * Zbudowane z RAW: SLOWKA[en] -> podstawowe tlumaczenie, WARIANTY[en] ->
 * dodatkowe akceptowane tlumaczenia (jesli sa). Sprawdzenie duplikatow
 * dzieje sie TUTAJ, raz, przy ladowaniu modulu - lepsze niz cicha nadpisana
 * wartosc w obiekcie, ktora zmniejszylaby liczbe slow bez zadnego ostrzezenia.
 */
export const SLOWKA = {};
export const WARIANTY = {};
{
  const widziane = new Set();
  for (const wpis of RAW) {
    const [en, pl, warianty] = wpis;
    if (widziane.has(en)) {
      throw new Error(`[slowka] Zduplikowane angielskie slowo w RAW: "${en}"`);
    }
    widziane.add(en);
    SLOWKA[en] = pl;
    if (warianty && warianty.length) WARIANTY[en] = warianty;
  }
}

export const ENGLISH_WORDS = Object.keys(SLOWKA);

/**
 * Wszystkie zaakceptowane, ZNORMALIZOWANE (normalizePolish) odpowiedzi dla
 * danego angielskiego slowa: podstawowe tlumaczenie z SLOWKA ORAZ wszystkie
 * wpisy z WARIANTY[word] (jesli sa). Wzorem getWarianty w countries.js.
 */
export function getAkceptowaneWarianty(word) {
  const podstawa = SLOWKA[word] ? [normalizePolish(SLOWKA[word])] : [];
  const dodatkowe = (WARIANTY[word] || []).map(normalizePolish);
  return [...new Set([...podstawa, ...dodatkowe])].filter(Boolean);
}

/** Dzieli juz znormalizowany (normalizePolish) tekst na tablice slow. */
function naSlowa(znormalizowanyTekst) {
  return znormalizowanyTekst.split(/\s+/).filter(Boolean);
}

/** Normalizuje i dzieli na slowa SUROWA odpowiedz z czatu. */
export function tokenizujOdpowiedzSlowka(tekst) {
  return naSlowa(normalizePolish(tekst));
}

/**
 * Indeks WSZYSTKICH akceptowanych wariantow WSZYSTKICH slowek, rozbitych na
 * slowa - {word, slowa}. Budowany raz przy ladowaniu modulu, wzorem
 * INDEKS_WARIANTOW w countries.js. Uzywany w src/tlumaczenia.js do
 * dopasowania odpowiedzi z czatu (dopasowanie CALYMI SLOWAMI, patrz komentarz
 * przy zawieraSekwencje w flagbattle.js - ta sama technika).
 */
export const INDEKS_WARIANTOW_SLOWEK = ENGLISH_WORDS.flatMap((word) =>
  getAkceptowaneWarianty(word).map((wariant) => ({ word, slowa: naSlowa(wariant) })),
).filter((wpis) => wpis.slowa.length > 0);
